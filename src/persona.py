def build_persona(extra_blocks: list[str] | None = None) -> str:
    """Compose the system prompt: identity core + optional few-shot/context
    blocks (Phase-5 JODA exemplars, associative context). Empty extras return
    the core byte-identical."""
    blocks = [SARA_PERSONA_AR, *(b for b in (extra_blocks or []) if b and b.strip())]
    return "\n\n".join(blocks)


