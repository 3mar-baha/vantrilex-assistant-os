def build_skill_guides() -> dict[str, str]:
    """All per-tool guides: {filename: content} — the skill-creator-shaped
    layer under the capabilities manifest."""
    return dict(_SKILLS)


async def sync_skill_guides(vault) -> int:
    """Upsert every per-tool guide into the live vault. Best-effort per
    file: one failure logs and skips; the count returned is what landed."""
    written = 0
    for filename, content in _SKILLS:
        try:
            await vault.upsert(
                f"{SARA_SKILLS_DIR}/{filename}",
                content,
                message=f"sara: skill guide sync {filename}",
            )
            written += 1
        except Exception as error:  # noqa: BLE001 — guides are best-effort
            logger.warning("skill guide {name} sync failed: {error}", name=filename, error=error)
    return written


async def read_skill_guide(vault, tool_name: str) -> str | None:
    """Consult ONE guide (progressive disclosure): the named tool's guide
    returns as-is; unknown names -> None (the caller answers honestly)."""
    from src.vault import split_frontmatter

    filename = f"{tool_name.strip().casefold()}.md"
    if filename not in {name for name, _ in _SKILLS}:
        return None
    try:
        text = await vault.read(f"{SARA_SKILLS_DIR}/{filename}")
    except FileNotFoundError:
        return None
    except Exception as error:  # noqa: BLE001
        logger.warning("skill guide read {name} failed: {error}", name=filename, error=error)
        return None
    body = split_frontmatter(text)[1].strip()
    return body or None
